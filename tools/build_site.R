# Builds the web version of the dashboard as a static site with shinylive.
#
# The package's R code and demo data are copied into a Shiny app that runs
# entirely in the visitor's browser through WebAssembly (webR), so nothing a
# visitor imports leaves their computer. The output is plain files that any
# static host can serve; the GitHub Actions workflow publishes them to Pages.
#
# From the package folder:
#   Rscript tools/build_site.R [output folder, default _site]
#
# Needs the shinylive package and the packages in DESCRIPTION.

args <- commandArgs(trailingOnly = TRUE)
out <- if (length(args)) args[[1]] else "_site"
if (!file.exists("DESCRIPTION") || !grepl("^Package: r401k", readLines("DESCRIPTION", n = 1))) {
  stop("Run this from the r401k package folder.", call. = FALSE)
}

app <- file.path(tempfile("r401k-web-"), "app")
dir.create(file.path(app, "R"), recursive = TRUE)
dir.create(file.path(app, "extdata"))

# The package's code, minus the roxygen package doc, which only makes sense
# inside an installed package.
sources <- setdiff(list.files("R", pattern = "\\.R$", full.names = TRUE), "R/r401k-package.R")
stopifnot(all(file.copy(sources, file.path(app, "R"))))
stopifnot(all(file.copy(list.files("inst/extdata", full.names = TRUE), file.path(app, "extdata"))))

version <- read.dcf("DESCRIPTION", fields = "Version")[[1]]
writeLines(c(
  sprintf("# Generated by tools/build_site.R from r401k %s. Edit the package, not this file.", version),
  "",
  "# Attached because the package code calls these without `pkg::`. dplyr comes",
  "# last so its filter() and lag() win, as they do inside the package.",
  "library(shiny)",
  "library(bslib)",
  "library(plotly)",
  "library(dplyr)",
  "",
  "# Used through `pkg::` in the package code; named here so shinylive bundles them.",
  "requireNamespace(\"DT\")",
  "requireNamespace(\"jsonlite\")",
  "requireNamespace(\"readxl\")",
  "requireNamespace(\"scales\")",
  "requireNamespace(\"zip\")",
  "",
  "r401k <- new.env()",
  "for (f in sort(list.files(\"R\", full.names = TRUE))) sys.source(f, envir = r401k)",
  "r401k$run_web_app(demo_dir = \"extdata\")"
), file.path(app, "app.R"))

unlink(out, recursive = TRUE)
shinylive::export(
  app, out,
  template_params = list(title = "r401k: 401(k) deposits vs. market returns")
)

# Pages serves files starting with an underscore only without Jekyll.
invisible(file.create(file.path(out, ".nojekyll")))
message(sprintf("Built %s (%.0f MB). Serve it with: httpuv::runStaticServer(\"%s\")",
                out, sum(file.size(list.files(out, recursive = TRUE, full.names = TRUE))) / 1e6, out))
